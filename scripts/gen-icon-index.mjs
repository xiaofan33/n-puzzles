/**
 * Scan the source directories for `<Namespace>.Xxx` usages and regenerate:
 *   _<namespace>.ts — selective re-exports of the icons in use
 *   index.ts        — re-exports via `export * as <Namespace>` for tree-shakeable namespace usage
 */
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { basename, join } from 'node:path'

const SCAN_DIRS = ['demos', 'src']
const LIBRARIES = {
  Lucide: 'lucide-react',
}

const SCRIPT_NAME = basename(import.meta.filename)
const ROOT_DIR = join(import.meta.dirname, '..')
const ICON_DIR = join(ROOT_DIR, 'shared/components/icons')
const SOURCE_FILE_RE = /\.(ts|tsx)$/
const USAGE_RE = new RegExp(
  `\\b(${Object.keys(LIBRARIES).join('|')})\\.([A-Za-z_$][\\w$]*)`,
  'g',
)

const iconsByLibrary = new Map(
  Object.keys(LIBRARIES).map(name => [name, new Set()]),
)

async function collectIcons(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      await collectIcons(path)
    } else if (SOURCE_FILE_RE.test(entry.name)) {
      const source = await readFile(path, 'utf-8')
      for (const [, name, icon] of source.matchAll(USAGE_RE)) {
        iconsByLibrary.get(name).add(icon)
      }
    }
  }
}

async function generateIndex() {
  for (const dir of SCAN_DIRS) await collectIcons(join(ROOT_DIR, dir))

  const libraries = [...iconsByLibrary].filter(([, icons]) => icons.size > 0)

  for (const [name, icons] of libraries) {
    const iconsContent = `// Auto-generated by scripts/${SCRIPT_NAME}
export {
${[...icons]
  .sort()
  .map(icon => `  ${icon},`)
  .join('\n')}
} from '${LIBRARIES[name]}'
`
    const iconsPath = join(ICON_DIR, `_${name.toLowerCase()}.ts`)
    await writeFile(iconsPath, iconsContent, 'utf-8')
    console.log(`Generated ${iconsPath} with ${icons.size} icons`)
  }

  const reExports = libraries
    .map(([name]) => `export * as ${name} from './_${name.toLowerCase()}'`)
    .join('\n')
  const indexContent = `// Auto-generated by scripts/${SCRIPT_NAME}
${reExports}
`
  const indexPath = join(ICON_DIR, 'index.ts')
  await writeFile(indexPath, indexContent, 'utf-8')
  console.log(`Generated ${indexPath} with ${libraries.length} namespaces`)
}

generateIndex().catch(console.error)
