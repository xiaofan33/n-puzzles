/**
 * Scan all component modules under the ui directory and generate:
 *   _parts.ts — barrel file listing every module
 *   index.ts  — re-exports via `export * as Shadcn` for tree-shakeable namespace usage
 */
import { readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const UI_DIR = join(import.meta.dirname, '..', 'shared/components/ui')
const PARTS_PATH = join(UI_DIR, '_parts.ts')
const INDEX_PATH = join(UI_DIR, 'index.ts')
const MODULE_NAME = 'Shadcn'

async function generateIndex() {
  const files = await readdir(UI_DIR)
  const modules = files
    .filter(f => f.endsWith('.tsx') || f.endsWith('.ts'))
    .filter(f => f !== 'index.ts' && f !== '_parts.ts')
    .map(f => f.replace(/\.\w+$/, ''))
    .sort()

  const reExports = modules.map(m => `export * from './${m}'`).join('\n')

  const partsContent = `// Auto-generated by scripts/gen-shadcn-index.mjs
// Pure re-export module — enables tree-shaking through the namespace chain.
${reExports}
`

  const indexContent = `// Auto-generated by scripts/gen-shadcn-index.mjs
export * as ${MODULE_NAME} from './_parts'
`

  await writeFile(PARTS_PATH, partsContent, 'utf-8')
  await writeFile(INDEX_PATH, indexContent, 'utf-8')
  console.log(
    `Generated ${PARTS_PATH} and ${INDEX_PATH} from ${modules.length} modules`,
  )
}

generateIndex().catch(console.error)
